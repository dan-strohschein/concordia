//! Regenerates `crates/jolt-sys/src/bindings.rs` (run from the repo root via `just jolt-bindgen`).

use std::path::Path;

const HEADERS: [&str; 1] = ["crates/jolt-sys/shim/concordia_jolt_ext.h"];
const OUT: &str = "crates/jolt-sys/src/bindings.rs";

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let mut hasher = blake3::Hasher::new();
    let mut builder = bindgen::Builder::default();
    for header in HEADERS {
        hasher.update(&std::fs::read(header)?);
        builder = builder.header(header);
    }
    let bindings = builder
        .allowlist_function("cj_.*|concordia_jolt_.*")
        .allowlist_type("Cj.*")
        .allowlist_var("CJ_.*")
        .rustified_enum("Cj(ShapeKind|Motion)")
        .layout_tests(false)
        .generate_comments(false)
        .generate()?;
    let header = format!(
        "// Generated by tools/jolt-bindgen (`just jolt-bindgen`); do not edit.\n// headers blake3: {}\n",
        hasher.finalize().to_hex()
    );
    std::fs::write(Path::new(OUT), header + &bindings.to_string())?;
    eprintln!("wrote {OUT}");
    Ok(())
}
