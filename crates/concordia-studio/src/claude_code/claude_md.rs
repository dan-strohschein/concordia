//! The managed block in `CLAUDE.md`; text outside the markers is never touched.

use super::agents::reviewers;
use crate::roster::Roster;

const BEGIN: &str = "<!-- concordia-studio:begin -->";
const END: &str = "<!-- concordia-studio:end -->";

/// `existing` with the Studio block replaced, or appended if it has none.
pub(crate) fn merge(existing: &str, roster: &Roster) -> String {
    let block = block(roster);
    match (existing.find(BEGIN), existing.find(END)) {
        (Some(start), Some(end)) if end > start => {
            format!(
                "{}{block}{}",
                &existing[..start],
                &existing[end + END.len()..]
            )
        }
        _ if existing.trim().is_empty() => format!("{block}\n"),
        _ => format!("{}\n\n{block}\n", existing.trim_end()),
    }
}

fn block(roster: &Roster) -> String {
    let team: Vec<String> = roster
        .roles()
        .iter()
        .map(|r| {
            format!(
                "- `{}` ({}, ×{}): {}",
                r.role, r.display_name, r.count, r.description
            )
        })
        .collect();
    let disabled: Vec<String> = roster
        .disabled()
        .iter()
        .map(|d| format!("`{}` ({})", d.role, d.reason))
        .collect();
    let disabled = match disabled.is_empty() {
        true => String::new(),
        false => format!("\nDisabled: {}.\n", disabled.join(", ")),
    };
    let review = roster
        .role(roster.director().as_str())
        .map(|r| reviewers(r, roster))
        .unwrap_or_default()
        .iter()
        .map(|p| format!("`{p}`"))
        .collect::<Vec<_>>()
        .join(" or ");
    format!(
        "{BEGIN}\n\
<!-- Generated by `concordia studio sync` from studio/; edit outside these markers. -->\n\
## Agent Studio\n\n\
This project is built by a team of agents inside Claude Code; no API key is needed. The main session is the **Director** (`{director}`).\n\n\
**Team** (`studio/team.toml`):\n{team}\n{disabled}\n\
**How work flows**\n\
1. The Director turns goals into tasks (`task_create`) with acceptance criteria and delegates each task to one role with the Agent tool, passing the task id.\n\
2. The role claims it (`task_claim`), works through the engine's MCP tools, records evidence (`task_comment`) and moves it to `in_review`.\n\
3. A reviewer the gates allow ({review}) approves it (`task_approve`) or rejects it with a reason (`task_reject`).\n\n\
**Rules**\n\
- Change the game world only through the `mcp__concordia__*` tools; every change is recorded with your actor.\n\
- Stay inside your role's write paths. `studio/`, `.claude/`, `.mcp.json` and `concordia.toml` are for humans.\n\
- `.claude/agents`, `.claude/skills` and this block are generated from `studio/`: edit the sources and run `concordia studio sync`.\n\
{END}",
        director = roster.director(),
        team = team.join("\n"),
        review = if review.is_empty() {
            "any reviewer".to_owned()
        } else {
            review
        },
    )
}
