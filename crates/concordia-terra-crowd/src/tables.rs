/// `[cos 2π/n, sin 2π/n, cos π/n, sin π/n]` for `n` clamped to 1..=32.
pub(crate) fn turns(n: usize) -> [f32; 4] {
    TURNS[n.clamp(1, TURNS.len()) - 1]
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn avoidance_pattern_tables_match_std() {
        // Each entry is std's f64 cos or sin rounded to f32 (exactly), and within 2.4e-7 (two
        // f32 epsilons) of what DetourCrowd computes in f32: cosf((1 / n) × π × 2), with its
        // π = 3.14159265f (the same f32 as `std`'s).
        for n in 1..=32usize {
            let full = 2.0 * std::f64::consts::PI / n as f64;
            let half = std::f64::consts::PI / n as f64;
            let want = [full.cos(), full.sin(), half.cos(), half.sin()].map(|x| x as f32);
            assert_eq!(turns(n), want, "n = {n}");
            let da = (1.0 / n as f32) * std::f32::consts::PI * 2.0;
            let detour = [da.cos(), da.sin(), (da * 0.5).cos(), (da * 0.5).sin()];
            for (got, d) in turns(n).iter().zip(detour) {
                assert!((got - d).abs() <= 2.4e-7, "n = {n}: {got} against {d}");
            }
        }
        assert_eq!(turns(0), turns(1), "clamped");
        assert_eq!(turns(40), turns(32), "clamped");
    }
}
