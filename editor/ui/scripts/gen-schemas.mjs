// Generates TypeScript types from the engine's JSON Schemas (`concordia schema --out`).
// Usage: node scripts/gen-schemas.mjs <schema dir>; writes src/api/generated/.
import { mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { compile } from "json-schema-to-typescript";

const source = process.argv[2];
if (!source) {
  console.error("usage: gen-schemas.mjs <schema dir>");
  process.exit(2);
}
const out = path.join(import.meta.dirname, "..", "src", "api", "generated");
const banner = "// Generated by `just editor-schemas` from the engine's JSON Schemas. Do not edit.";

/** PascalCase identifier from a file stem such as `capture.screenshot.params`. */
const typeName = (stem) =>
  stem
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join("");

async function generate(dir, prefix) {
  const files = (await readdir(dir)).filter((f) => f.endsWith(".schema.json")).sort();
  const written = [];
  for (const file of files) {
    const schema = JSON.parse(await readFile(path.join(dir, file), "utf8"));
    const name = typeName(prefix + file.replace(/\.schema\.json$/, ""));
    delete schema.title; // name the root after the file, not the Rust type
    const ts = await compile(schema, name, { bannerComment: banner, additionalProperties: false, format: false });
    await writeFile(path.join(out, `${name}.ts`), ts);
    written.push(name);
  }
  return written;
}

await rm(out, { recursive: true, force: true });
await mkdir(out, { recursive: true });
const types = await generate(source, "");
const methods = await generate(path.join(source, "methods"), "method.");
console.log(
  `generated ${types.length} type files and ${methods.length} method files into ${path.relative(process.cwd(), out)}`,
);
